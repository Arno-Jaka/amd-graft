"""Popup preview of a Gemma-converted file.

The AI version is shown in its own modal so it can be read beside the
deterministic output without either being mistaken for the other. The comment
list beneath the code is the model's own account of what it changed; it is
labelled as such and never presented as measured evidence.
"""

from __future__ import annotations

from typing import Any, ClassVar

from textual import events
from textual.app import ComposeResult
from textual.containers import Vertical, VerticalScroll
from textual.screen import ModalScreen
from textual.widgets import Button, Static

from graft.tui.screens.results import numbered_source


class AIConversionPopup(ModalScreen[None]):
    """Show a Gemma-converted file with the model's change notes."""

    BINDINGS: ClassVar[list[tuple[str, str, str]]] = [
        ("escape", "dismiss_popup", "Close"),
    ]

    def __init__(
        self, filename: str, code: str, comments: list[dict[str, Any]]
    ) -> None:
        super().__init__()
        self.filename = filename
        self.code = code
        self.comments = comments or []

    def compose(self) -> ComposeResult:
        with Vertical(id="ai-popup-card"):
            yield Static("AI-CONVERTED VERSION · GOOGLE GEMMA", id="ai-popup-eyebrow")
            yield Static(
                f"{self.filename} · {len(self.code.splitlines())} line(s)",
                id="ai-popup-title",
                markup=False,
            )
            yield Static(
                "This file was generated by a language model. It may be wrong. "
                "The deterministic report and any GPU parity/benchmark results "
                "are the evidence; this version is a proposal.",
                id="ai-popup-disclaimer",
                markup=False,
            )
            with VerticalScroll(id="ai-popup-scroll"):
                yield Static(
                    numbered_source(self.code), id="ai-popup-code", markup=False
                )
                if self.comments:
                    yield Static(
                        "WHAT THE MODEL SAYS IT CHANGED", classes="ai-popup-section"
                    )
                    for comment in self.comments:
                        line = comment.get("line")
                        where = f"line {line}" if line else "general"
                        severity = str(comment.get("severity", "review")).upper()
                        yield Static(
                            f"{severity} · {where} · {comment.get('title', 'Change')}",
                            classes="ai-popup-comment-title",
                            markup=False,
                        )
                        if comment.get("comment"):
                            yield Static(
                                str(comment["comment"]),
                                classes="ai-popup-comment",
                                markup=False,
                            )
            with Vertical(id="ai-popup-actions"):
                yield Button("Copy file", id="ai-popup-copy")
                yield Button("Dismiss", id="ai-popup-dismiss")

    def on_button_pressed(self, event: Button.Pressed) -> None:
        if event.button.id == "ai-popup-copy":
            self.app.copy_to_clipboard(self.code)
            self.notify(f"Copied {self.filename} to the clipboard")
        elif event.button.id == "ai-popup-dismiss":
            self.dismiss()

    def action_dismiss_popup(self) -> None:
        self.dismiss()

    def on_mouse_down(self, event: events.MouseDown) -> None:
        if event.button == 3:
            self.dismiss()


__all__ = ["AIConversionPopup"]
